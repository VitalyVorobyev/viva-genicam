//! The UI's TypeScript types, generated from the Rust types the backend sends
//! (backlog ST-28).
//!
//! `cargo test` fails while `ui/viva-studio-ui/src/generated/ipc.ts` differs
//! from what these types produce. After changing one of them, run
//! `UPDATE_BINDINGS=1 cargo test bindings` here and commit the file.

use ts_rs::{Config, TS};

const OUT: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../../ui/viva-studio-ui/src/generated/ipc.ts"
);

fn render() -> String {
    // `serde_json` writes 64-bit integers as JSON numbers.
    let cfg = Config::new().with_large_int("number");
    let mut out = String::from(
        "// @generated by `apps/viva-studio-tauri/src-tauri/src/bindings.rs` from the\n\
         // Rust types the backend sends. Do not edit: change the Rust type, then run\n\
         // `UPDATE_BINDINGS=1 cargo test bindings` in `src-tauri`.\n\n",
    );
    macro_rules! declare {
        ($($ty:ty),* $(,)?) => {
            $(
                out.push_str("export ");
                out.push_str(<$ty>::decl(&cfg).trim_end());
                out.push_str("\n\n");
            )*
        };
    }
    declare!(
        serde_json::Value,
        // The service's contract (`viva-zenoh-api`).
        viva_zenoh_api::FeatureState,
        viva_zenoh_api::NumericRange,
        viva_zenoh_api::CommandResult,
        viva_zenoh_api::AcquisitionStatus,
        viva_zenoh_api::StreamCounters,
        viva_zenoh_api::ImageMeta,
        viva_zenoh_api::FrameMetadata,
        viva_zenoh_api::FrameChunk,
        viva_zenoh_api::FrameFeature,
        // The UiGraph contract (`viva_xml_model`).
        viva_xml_model::UiGraph,
        viva_xml_model::UiNode,
        viva_xml_model::UiNodeKind,
        viva_xml_model::UiCategory,
        viva_xml_model::NumericConstraints,
        viva_xml_model::EnumEntry,
        viva_xml_model::UiSkippedNode,
        // Command results.
        crate::commands::xml_model::ParseXmlResponse,
        crate::commands::xml_model::ModelSummary,
        crate::state::Diag,
        crate::state::DiagLevel,
        crate::state::device_state::DeviceInfo,
        crate::state::device_state::ConnectionState,
        crate::state::device_state::ConnectionAccess,
        crate::state::device_state::StreamerInfo,
        crate::commands::backend::BackendStatus,
        crate::backend::BackendMode,
        crate::backend::NetworkConfig,
        crate::commands::sfnc_groups::SfncGroup,
        crate::commands::sfnc_groups::SfncFeature,
        // Event payloads.
        crate::state::device_state::DisconnectReason,
        crate::state::device_state::ApiVersionMismatch,
        crate::state::events::FeatureStateChanged,
        crate::state::events::FeaturesInvalidated,
        crate::state::events::DeviceLost,
        crate::state::events::DeviceReconnected,
        crate::state::events::ZenohSessionLost,
        crate::state::events::ZenohSessionRestored,
    );
    out.push_str("/** Every event the backend sends, by name, with its payload. */\n");
    out.push_str("export type StudioEvents = {\n");
    for (name, ty) in crate::state::events::all(&cfg) {
        out.push_str(&format!("  \"{name}\": {ty};\n"));
    }
    out.push_str("};\n");
    out.push_str("\n/** Registered Tauri commands: wire arguments and successful response. */\n");
    out.push_str("export type StudioCommands = {\n");
    for (name, signature) in crate::command_bindings::all(&cfg) {
        out.push_str(&format!("  \"{name}\": {signature};\n"));
    }
    out.push_str("};\n");
    // ts-rs leaves a space before each line break.
    out.lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        + "\n"
}

#[test]
fn bindings_are_current() {
    let fresh = render();
    if std::env::var_os("UPDATE_BINDINGS").is_some() {
        std::fs::write(OUT, &fresh).expect("write the generated bindings");
        return;
    }
    // A Windows checkout may have turned the committed file's line endings.
    let committed = std::fs::read_to_string(OUT)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    assert!(
        committed == fresh,
        "{OUT} is stale: run `UPDATE_BINDINGS=1 cargo test bindings` in src-tauri and commit the result"
    );
}
